# make_pb_values.py | v1.0.1
# Writes tts/pb_values.csv: the whole-phrase value clips Pilot_Banter v2.0.0 chains into its
# spoken checks ("Fuel..." + "nine point eight" + "Plenty of gas."). One clip per value, so
# Piper speaks each number with natural prosody instead of digit tokens.
#
#   python tools/pilot_banter/make_pb_values.py      (then: python tts/make_clips.py --set pb)
#
# ids (Pilot_Banter V*() helpers build the same names):
#   v_fuel_<t>    t = 0..200     fuel in hundreds of lb: v_fuel_98 = "nine point eight"
#   v_kft_<n>     n = 1..50      "twenty-two thousand"
#   v_nm_<n>      n = 1..99, 100..400 step 10      "forty miles"
#   v_min_<n>     n = 1..60      "twelve minutes"
#   v_early_<n> / v_late_<n>  n = 1..30   "about two minutes early"; v_ontime "right on time"
#   v_pct_<n>     n = 50..110    "eighty-nine percent" (engine rpm)
#   v_rate_<n>    n = 60..400 step 10   lb/min "one sixty a minute"
#   v_stores_<n>  n = 0..8       "two weapons left" / n = 0: "winchester"
#   v_code_<c>    laser codes in CODES
#   snd_*         synthesized noises (make_clips text <COUGH> etc.)
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'tts', 'pb_values.csv')
V = 'PILOT_IN'
CODES = (1688,)

ONES = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten',
        'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen',
        'nineteen']
TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety']


def words(n):
    """0..999 as American English words, no 'and'."""
    if n < 20:
        return ONES[n]
    if n < 100:
        t, o = divmod(n, 10)
        return TENS[t] + ('' if o == 0 else ' ' + ONES[o])   # no hyphen: Piper pauses at '-' (2026-10-31)
    h, r = divmod(n, 100)
    return ONES[h] + ' hundred' + ('' if r == 0 else ' ' + words(r))


def rate_words(n):
    """lb/min the way a pilot says it: 160 -> 'one sixty', 200 -> 'two hundred', 310 -> 'three ten'."""
    h, r = divmod(n, 100)
    if r == 0:
        return ONES[h] + ' hundred'
    return ONES[h] + ' ' + words(r)


def main():
    rows = []
    add = lambda i, t: rows.append('%s;%s;%s' % (i, V, t))
    for t in range(0, 201):
        a, b = divmod(t, 10)
        add('v_fuel_%d' % t, ('point %s' % ONES[b]) if a == 0 else '%s point %s' % (words(a), ONES[b]))
    for n in range(1, 51):
        add('v_kft_%d' % n, '%s thousand' % words(n))
    for n in list(range(1, 100)) + list(range(100, 401, 10)):
        add('v_nm_%d' % n, 'one mile' if n == 1 else '%s miles' % words(n))
    for n in range(1, 61):
        add('v_min_%d' % n, 'one minute' if n == 1 else '%s minutes' % words(n))
    for n in range(1, 31):
        add('v_early_%d' % n, 'about a minute early' if n == 1 else 'about %s minutes early' % words(n))
        add('v_late_%d' % n, 'about a minute late' if n == 1 else 'about %s minutes late' % words(n))
    add('v_ontime', 'right on time')
    for n in range(50, 111):
        add('v_pct_%d' % n, '%s percent' % words(n))
    for n in range(60, 401, 10):
        add('v_rate_%d' % n, '%s a minute' % rate_words(n))
    add('v_stores_0', 'And... winchester.')
    add('v_stores_1', 'One weapon left.')
    for n in range(2, 9):
        add('v_stores_%d' % n, '%s weapons left.' % words(n).capitalize())
    for c in CODES:
        add('v_code_%d' % c, ' '.join(ONES[int(d)] for d in str(c)))
    # synthesized noises (make_clips: no Piper, ffmpeg source + cockpit chain)
    for i, tag in enumerate(('<COUGH2>', '<COUGH1>', '<THROAT>', '<SNIFF>', '<BREATH>', '<COUGH2>'), 1):
        add('snd_%d' % i, tag)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# pb_values.csv | generated by tools/pilot_banter/make_pb_values.py - do not edit by hand\n')
        f.write('# id;voice;text   (value clips chained by Pilot_Banter v2.0.0; snd_* = synthesized noises)\n')
        f.write('\n'.join(rows) + '\n')
    print('%d rows -> %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
